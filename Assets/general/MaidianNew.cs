                Debug.Log("openidlog==fail== " + www.error);
                callback(false, null);
            }
            else
            {
                try
                {
                    var response = JsonUtility.FromJson<OpenIdResponse>(www.downloadHandler.text);
                    callback(true, response);
                }
                catch (Exception ex)
                {
                    Debug.LogError("解析openid响应出错: " + ex.Message);
                    callback(false, null);
                }
            }
        }
    }

