    private IEnumerator SendConversionRequest(string eventType, string clickid, long timestamp, Action<bool, string> callback)
    {
        var data = new ConversionData
        {
            event_type = eventType,
            context = new Context
            {
                ad = new Ad
                {
                    callback = clickid
                }
            },
            timestamp = timestamp
        };

        string json = JsonUtility.ToJson(data);
        byte[] postData = System.Text.Encoding.UTF8.GetBytes(json);

        Dictionary<string, string> headers = new Dictionary<string, string>();
        headers.Add("Content-Type", "application/json");

        using (var www = new UnityEngine.Networking.UnityWebRequest("https://analytics.oceanengine.com/api/v2/conversion", "POST"))
        {
            www.uploadHandler = new UnityEngine.Networking.UploadHandlerRaw(postData);
            www.downloadHandler = new UnityEngine.Networking.DownloadHandlerBuffer();
            foreach (var header in headers)
            {
                www.SetRequestHeader(header.Key, header.Value);
            }

            yield return www.SendWebRequest();

            if (www.isNetworkError || www.isHttpError)
            {
                callback(false, www.error);
            }
            else
            {
                callback(true, www.downloadHandler.text);
            }
        }
    }

    private IEnumerator SendOpenIdLog(string appid, string nickName, string code, string anonymousCode, TTSystemInfo sysinfores, Action<bool, OpenIdResponse> callback)
    {
        var query = $"?appid={Uri.EscapeDataString(appid)}" +
                    $"&nickName={Uri.EscapeDataString(nickName)}" +
                    $"&code={Uri.EscapeDataString(code)}" +
                    $"&anonymousCode={Uri.EscapeDataString(anonymousCode)}" +
                    $"&system={Uri.EscapeDataString(sysinfores.system)}" +
                    $"&platform={Uri.EscapeDataString(sysinfores.platform)}" +
                    $"&brand={Uri.EscapeDataString(sysinfores.brand)}" +
                    $"&modelx={Uri.EscapeDataString(sysinfores.model)}" +
                    $"&version={Uri.EscapeDataString(sysinfores.ttVersion)}" +
                    $"&appName={Uri.EscapeDataString(sysinfores.hostName)}" +
                    $"&SDKVersion={AdMgr.Instance.MultitonRewardTimes}" +
                    $"&SDKVersion={Uri.EscapeDataString(sysinfores.sdkVersion)}";//$"&appName={Uri.EscapeDataString(sysinfores.appName)}" +

        using (var www = UnityEngine.Networking.UnityWebRequest.Get("https://ecpm.sangliangban.com/openid/openlog/insertlog" + query))
        {
            yield return www.SendWebRequest();

            if (www.isNetworkError || www.isHttpError)
            {
                Debug.Log("openidlog==fail== " + www.error);
                callback(false, null);
            }
            else
            {
                try
                {
                    var response = JsonUtility.FromJson<OpenIdResponse>(www.downloadHandler.text);
                    callback(true, response);
                }
                catch (Exception ex)
                {
                    Debug.LogError("解析openid响应出错: " + ex.Message);
                    callback(false, null);
                }
            }
        }
    }

