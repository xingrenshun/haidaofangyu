using StarkSDKSpace;
using System.Collections;
using System.Collections.Generic;
using TTSDK;
using TTSDK.UNBridgeLib.LitJson;
using UnityEngine;
using UnityEngine.UI;

public class SideBar : MonoBehaviour
{
    public static SideBar instance;
    public string LaunchFrom;
    public string Location;
    //public Button GetBtn;
    public Button LookBtn;
    public bool isSideBar = false;
    public bool IsGetSideBarGift;

    // 缓存委托，防止 IL2CPP/WebGL 下被 GC 或元数据丢失
    private System.Action onGoSideBarSuccess;
    private System.Action onGoSideBarComplete;
    private System.Action<int, string> onGoSideBarError;
    private System.Action<bool> onShowRevisitGuide;

    private void Awake()
    {
        instance = this;
        IsGetSideBarGift = false;

        onGoSideBarSuccess = OnGoSideBarSuccess;
        onGoSideBarComplete = OnGoSideBarComplete;
        onGoSideBarError = OnGoSideBarError;
        onShowRevisitGuide = OnShowRevisitGuide;
    }
    void Start()
    {
        // isSideBar = false;
        ReturnToScene();
        Debug.Log("start函数已调用");
    }

    void Update()
    {
        GetBtnShow();
        //Debug.Log(isSideBar);
    }
    public void GoSideBar()
    {
        try
        {
            var data = new JsonData
            {
                ["scene"] = "sidebar",
            };
            TT.NavigateToScene(data, onGoSideBarSuccess, onGoSideBarComplete, onGoSideBarError);
        }
        catch (System.Exception e)
        {
            Debug.LogError("跳转到侧边栏异常: " + e.Message);
        }
    }

    private void OnGoSideBarSuccess()
    {
        Debug.Log("navigate to scene success");
    }

    private void OnGoSideBarComplete()
    {
        Debug.Log("navigate to scene complete");
    }

    private void OnGoSideBarError(int errCode, string errMsg)
    {
        Debug.Log($"navigate to scene error, errCode:{errCode}, errMsg:{errMsg}");
    }
    public void ShowTeach()
    {
        TT.ShowRevisitGuide(onShowRevisitGuide);
    }

    private void OnShowRevisitGuide(bool res)
    {
        Debug.Log($"ShowRevisitGuide result: {res}");
    }
    public void ReturnToScene()
    {
        TT.GetAppLifeCycle().OnShow += OnShowOneParam;
        //StarkSDKSpace.StarkSDK.API.GetStarkAppLifeCycle().OnShowWithDict += OnShowOneParam;
        LaunchFrom = TT.s_ContainerEnv.GetLaunchFrom();
        Location = TT.s_ContainerEnv.GetLocation();
        Debug.Log("LaunchFrom :" + LaunchFrom);
        Debug.Log("Location :" + Location);
        IsSideBarBack();
        //field3.text += "LaunchFrom = " + LaunchFrom;
        //field3.text += "Location = " + Location;
    }
    private void OnShowOneParam(Dictionary<string, object> param)
    {
        //field3.text += $"OnShowOneParam-->${param.ToString()}";
    }
    public void IsSideBarBack()
    {
        if (LaunchFrom == "homepage" || Location == "sidebar_card")
        {
            isSideBar = true;
        }
        else
        {
            isSideBar = false;
        }
    }
    private void GetBtnShow()
    {
        if (isSideBar)
        {
            //GetBtn.gameObject.SetActive(true);
            LookBtn.gameObject.SetActive(true);
        }
        else
        {
            //GetBtn.gameObject.SetActive(false);
            LookBtn.gameObject.SetActive(true);
        }
        if (!IsGetSideBarGift)
        {
            //GetBtn.gameObject.SetActive(true);
        }
        else  
        {
            //GetBtn.gameObject.SetActive(false);
            LookBtn.gameObject.SetActive(true);
        }
    }
    public void GetGoin()
    {
        if (!IsGetSideBarGift)
        {
            IsGetSideBarGift = true;
            //PlayerPrefs.SetInt("Coins", PlayerPrefs.GetInt("Coins") + 10000);
            
            //GetBtn.GetComponentInChildren<Text>().text = "已领取";
            //GetBtn.interactable = false;
        }
        else 
        {
            return;
        }
    }
}
