using StarkSDKSpace;
using System.Collections;
using System.Collections.Generic;
using TTSDK;
using UnityEngine;
using static StarkSDKSpace.CanIUse.StarkAdManager;

public class InterstitialAd : MonoBehaviour
{
    private string tableScreenAdid = "55gtlfoqx913od90li";
    static bool isFirstEnter = true;
    public GameObject TipNoAd;
    private GameObject TipNoAdInstance;
    TTInterstitialAd interstitialAd;
    //public GameObject CanvasNode;

    // 缓存委托，防止 IL2CPP/WebGL 下目标丢失
    private AdLoadDelegate onInterLoad;

    // Start is called before the first frame update
    void Start()
    {
        onInterLoad = OnInterstitialLoad;
        if (isFirstEnter)
        {
            StartCoroutine(RepeatOpenInterstitialAd());
            //StartCoroutine(OpenInterstitialAd());
        }
    }

    // Update is called once per frame
    void Update()
    {
        
    }

    private IEnumerator RepeatOpenInterstitialAd()
    {
        while (true)
        {
            float randomDelay = Random.Range(300f, 1200f);
            // 等待 x 分钟
            yield return new WaitForSeconds(randomDelay); // 1200 秒等于 20 分钟

            // 执行打开广告的方法
            yield return StartCoroutine(OpenInterstitialAd());
        }
    }

    public void ShowAd()
    {
        tableScreenAdid = VideData.Instance.GetTableScreenVide();
        // 创建插页广告实例，并传递广告ID，错误回调和关闭回调
        interstitialAd = TT.CreateInterstitialAd(tableScreenAdid, errCallback, closeCallback);

        // 加载广告
        interstitialAd.Load();

        // 在广告加载成功后展示广告
        interstitialAd.OnLoad += onInterLoad;
    }

    private void OnInterstitialLoad()
    {
        // 广告加载成功，展示广告
        interstitialAd?.Show();
    }

    private void errCallback(int errorCode, string errorMessage)
    {
        // 处理广告加载失败的情况
        Debug.Log("观看广告失败，错误码：" + errorCode + " 错误信息：" + errorMessage);
        // 加载预制体并显示
        if (TipNoAd != null)
        {
            TipNoAdInstance = Instantiate(TipNoAd, transform.position, Quaternion.identity);

            // 等待 1 秒后销毁提示框
            StartCoroutine(DestroyErrorMessageAfterDelay());
        }

    }

    private void closeCallback()
    {
        MaidianNew.MaidianBackCallback(" ");
        // 处理广告关闭后的回调
        Debug.Log("广告关闭");
        if (interstitialAd != null)
        {
            interstitialAd.Destroy();
        }
        interstitialAd = null;
    }

    private IEnumerator OpenInterstitialAd()
    {
        // 等待指定的时间
        yield return null;

        // 这里执行你想要延迟执行的操作
        UnityEngine.Debug.Log("1帧后执行的操作");

        ShowAd();
        //isFirstEnter = false;
    }

    // 延迟销毁错误提示框
    private IEnumerator DestroyErrorMessageAfterDelay()
    {
        yield return new WaitForSeconds(1f);  // 等待 1 秒钟后销毁
        if (TipNoAdInstance != null)
        {
            Destroy(TipNoAdInstance);  // 销毁实例化的提示框
        }
    }
}
